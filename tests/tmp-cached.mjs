import { startServer } from "./lib/server.mjs";
import { chromium } from "playwright";
const server = await startServer();
const browser = await chromium.launch({ args: ["--no-sandbox"] });
const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, serviceWorkers: "block" });
const page = await ctx.newPage();
const errs = [];
page.on("pageerror", e => errs.push(String(e)));
page.on("console", m => { if (m.type() === "error") errs.push(m.text()); });
await ctx.addInitScript(() => {
  localStorage.setItem("talk.model.v1", JSON.stringify({ remember:true, baseUrl:"https://stub.local/v1", apiKey:"sk-test-1234567890123456", model:"mock-model", activeProfileId:"stub", profiles:[{id:"stub", name:"stub", baseUrl:"https://stub.local/v1", apiKey:"sk-test-1234567890123456", model:"mock-model", protocol:"openai"}] }));
});
await page.route("https://stub.local/**", async route => {
  const body = JSON.parse(route.request().postData() || "{}");
  const fixtures = await import("node:fs");
  const word = JSON.parse(fixtures.readFileSync("tests/fixtures/word-obfuscate.json", "utf8"));
  await route.fulfill({ status:200, contentType:"application/json", body: JSON.stringify({ choices:[{message:{content: JSON.stringify(word)}}], usage:{total_tokens:460} }) });
});
await page.goto(server.origin + "/", { waitUntil: "domcontentloaded" });
await page.waitForSelector("#search-input");
await page.fill("#search-input", "obfuscate");
await page.keyboard.press("Enter");
await page.waitForSelector(".result-page", { timeout: 15000 });
console.log("hash", await page.evaluate(() => location.hash));
await page.waitForTimeout(500);
await page.reload({ waitUntil: "networkidle" });
await page.waitForTimeout(800);
console.log("after reload", await page.evaluate(() => ({ hash: location.hash, title: document.querySelector(".word-title")?.textContent, miss: !![...document.querySelectorAll("*")].find(e => e.textContent === "离线词库还没收录。") })));
console.log("errors", errs.slice(0, 4));
await browser.close(); await server.stop();
