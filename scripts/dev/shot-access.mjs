import { chromium } from "playwright";
import { startServer } from "../../tests/lib/server.mjs";
import { readFileSync } from "node:fs";
const server = await startServer();
const browser = await chromium.launch({ args: ["--no-sandbox"] });
const ctx = await browser.newContext({ viewport: { width: 430, height: 932 }, deviceScaleFactor: 2, serviceWorkers: "block" });
await ctx.addInitScript(() => localStorage.setItem("talk.theme.v1", "rhineaccess"));
const page = await ctx.newPage();
const word = JSON.parse(readFileSync("tests/fixtures/word-obfuscate.json", "utf8"));
await page.route("**/chat/completions", (r) => r.fulfill({ status: 200, contentType: "application/json", body: JSON.stringify({ choices: [{ message: { content: JSON.stringify(word) } }], usage: { total_tokens: 460 } }) }));
await page.goto(server.origin + "/", { waitUntil: "domcontentloaded" });
await page.waitForSelector(".screen"); await page.waitForTimeout(600);
await page.screenshot({ path: "preview/acc2-home.png" });
await page.fill("#search-input", "obfuscate");
await page.press("#search-input", "Enter");
await page.waitForSelector(".result-page", { timeout: 15000 });
await page.waitForTimeout(900);
await page.screenshot({ path: "preview/acc2-word.png", fullPage: true });
await page.evaluate(() => { const s = document.querySelector(".screen"); s.scrollTop = s.scrollHeight; });
await page.waitForTimeout(500);
await page.screenshot({ path: "preview/acc2-foot.png" });
await page.goto(server.origin + "/#/theme/access-01", { waitUntil: "domcontentloaded" });
await page.waitForTimeout(800);
await page.screenshot({ path: "preview/acc2-poster.png", fullPage: true });
await browser.close(); await server.stop();
